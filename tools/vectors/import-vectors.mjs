/*
 * tools/vectors/import-vectors.mjs
 *
 * PURPOSE
 *   Maintainer-only script. Converts official upstream test-vector files into
 *   classic-script data files under tests/vectors/, because pages opened from
 *   file:// cannot fetch() JSON. Vectors must come from the specification
 *   authors, never from the library under test (that would be circular).
 *
 * USAGE
 *   node tools/vectors/import-vectors.mjs <dir>
 *   <dir> must contain files downloaded from pinned commits:
 *     bip39-vectors.json  https://github.com/trezor/python-mnemonic  vectors.json
 *     trezor.sha          the trezor/python-mnemonic commit hash used
 *     bip-0032.mediawiki  https://github.com/bitcoin/bips  bip-0032.mediawiki
 *     bips.sha            the bitcoin/bips commit hash used
 *
 * OUTPUT
 *   tests/vectors/bip39-trezor.js   window.WG.vectors.bip39Trezor
 *   tests/vectors/bip32.js          window.WG.vectors.bip32
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const srcDir = process.argv[2];
if (!srcDir) {
  console.error('usage: node import-vectors.mjs <download-dir>');
  process.exit(2);
}
const outDir = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..', 'tests', 'vectors');

/** Read a pinned commit hash and make sure it really looks like one. */
function readSha(name) {
  const sha = readFileSync(join(srcDir, name), 'utf8').trim();
  if (!/^[0-9a-f]{40}$/.test(sha)) throw new Error(name + ' is not a 40-hex commit hash');
  return sha;
}

/** Wrap a data object into a commented classic script that registers it. */
function emit(file, key, header, data) {
  const body = [
    '/*',
    ' * tests/vectors/' + file + '  --  GENERATED by tools/vectors/import-vectors.mjs, do not edit.',
    ...header.map((l) => ' * ' + l),
    ' */',
    "'use strict';",
    'window.WG.vectors.' + key + ' = ' + JSON.stringify(data, null, 2) + ';',
    '',
  ].join('\n');
  writeFileSync(join(outDir, file), body);
  console.log('wrote tests/vectors/' + file);
}

// ---- BIP39 (Trezor reference vectors, English, passphrase "TREZOR") -------
{
  const sha = readSha('trezor.sha');
  const raw = JSON.parse(readFileSync(join(srcDir, 'bip39-vectors.json'), 'utf8'));
  const cases = raw.english.map(([entropy, mnemonic, seed, xprv]) => ({ entropy, mnemonic, seed, xprv }));
  for (const c of cases) {
    if (!/^[0-9a-f]+$/.test(c.entropy) || !/^[0-9a-f]{128}$/.test(c.seed) || !c.xprv.startsWith('xprv')) {
      throw new Error('unexpected BIP39 vector shape');
    }
  }
  emit('bip39-trezor.js', 'bip39Trezor', [
    'Source: https://github.com/trezor/python-mnemonic/blob/' + sha + '/vectors.json',
    'Each case: entropy -> mnemonic (English) -> seed with passphrase "TREZOR" -> BIP32 root xprv.',
  ], { source: 'trezor/python-mnemonic@' + sha, passphrase: 'TREZOR', cases });
}

// ---- BIP32 (test vectors 1-4 from the BIP text) -----------------------------
{
  const sha = readSha('bips.sha');
  const text = readFileSync(join(srcDir, 'bip-0032.mediawiki'), 'utf8');
  const vectors = [];
  let cur = null;
  let chain = null;
  for (const line of text.split(/\r?\n/)) {
    let m;
    if ((m = line.match(/^===Test vector (\d+)===/))) {
      cur = { name: 'Test vector ' + m[1], seed: null, chains: [] };
      vectors.push(cur);
      chain = null;
    } else if (cur && (m = line.match(/^Seed \(hex\): ([0-9a-f]+)/))) {
      cur.seed = m[1];
    } else if (cur && (m = line.match(/^\* Chain (\S+)/))) {
      // "m/0<sub>H</sub>/1" -> "m/0'/1" (the notation @scure/bip32 accepts)
      chain = { path: m[1].replace(/<sub>H<\/sub>/g, "'"), xpub: null, xprv: null };
      cur.chains.push(chain);
    } else if (chain && (m = line.match(/^\*\* ext pub: (\S+)/))) {
      chain.xpub = m[1];
    } else if (chain && (m = line.match(/^\*\* ext prv: (\S+)/))) {
      chain.xprv = m[1];
    }
  }
  // Vector 5 lists invalid keys (no seed); only seed-based vectors are kept.
  const valid = vectors.filter((v) => v.seed && v.chains.length && v.chains.every((c) => c.xpub && c.xprv));
  if (valid.length < 4) throw new Error('expected at least 4 BIP32 seed vectors, got ' + valid.length);
  emit('bip32.js', 'bip32', [
    'Source: https://github.com/bitcoin/bips/blob/' + sha + '/bip-0032.mediawiki',
    'Each vector: master seed -> list of derivation paths with expected xpub/xprv.',
  ], { source: 'bitcoin/bips@' + sha, vectors: valid });
}
