/*
 * tools/vectors/import-vectors.mjs
 *
 * PURPOSE
 *   Maintainer-only script. Converts official upstream test vectors (and the
 *   two non-BIP39 wordlists the app needs) into classic-script files, because
 *   pages opened from file:// cannot fetch() JSON. Vectors must come from the
 *   specification authors or independent reference implementations, never
 *   from the library under test (that would be circular).
 *
 * USAGE
 *   node tools/vectors/import-vectors.mjs <dir>
 *   <dir> holds files downloaded from pinned commits plus one "<name>.sha"
 *   file per upstream repo containing that commit hash:
 *
 *   trezor.sha            trezor/python-mnemonic          bip39-vectors.json
 *   bips.sha              bitcoin/bips                    bip-0032/0038/0084/0086.mediawiki
 *   slips.sha             satoshilabs/slips               slip-0010.md
 *   shamir.sha            trezor/python-shamir-mnemonic   slip39-vectors.json, slip39-wordlist.txt
 *   stellar.sha           stellar/stellar-protocol        sep-0005.md
 *   cips.sha              cardano-foundation/CIPs         cip3-icarus.md
 *   monero.sha            monero-project/monero           monero-english.h, monero-wallet.py
 *   trezor-firmware.sha   trezor/trezor-firmware          test_getaddress.py, test_getaddress_segwit_native.py,
 *                                                         test_get_address.py (ripple), get_base_address.json (cardano),
 *                                                         common_tests_fixtures_{ethereum_getaddress,solana_get_address}.json
 *   iancoleman.sha        iancoleman/bip39                ianc-tests.js
 *
 * OUTPUT
 *   tests/vectors/*.js    window.WG.vectors.<name> = {...}   (test data only)
 *   js/data/*.js          wordlists used by the app itself (Monero, SLIP-39)
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const srcDir = process.argv[2];
if (!srcDir) {
  console.error('usage: node import-vectors.mjs <download-dir>');
  process.exit(2);
}
const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const vecDir = join(repo, 'tests', 'vectors');
const dataDir = join(repo, 'js', 'data');
mkdirSync(vecDir, { recursive: true });
mkdirSync(dataDir, { recursive: true });

/** Read a downloaded file as UTF-8 text. */
const read = (name) => readFileSync(join(srcDir, name), 'utf8');

/** Read a pinned commit hash and make sure it really looks like one. */
function sha(name) {
  const s = read(name).trim();
  if (!/^[0-9a-f]{40}$/.test(s)) throw new Error(name + ' is not a 40-hex commit hash');
  return s;
}

/** Throw with a message unless cond holds (keeps parsers honest). */
function check(cond, msg) {
  if (!cond) throw new Error('import check failed: ' + msg);
}

/** Write a commented classic script that registers a test-vector object. */
function emitVector(file, key, header, data) {
  const body = [
    '/*',
    ' * tests/vectors/' + file + '  --  GENERATED by tools/vectors/import-vectors.mjs, do not edit.',
    ...header.map((l) => ' * ' + l),
    ' */',
    "'use strict';",
    'window.WG.vectors.' + key + ' = ' + JSON.stringify(data, null, 2) + ';',
    '',
  ].join('\n');
  writeFileSync(join(vecDir, file), body);
  console.log('wrote tests/vectors/' + file);
}

/** Write a commented classic script that defines app data via WG.define. */
function emitData(file, moduleName, header, data) {
  const body = [
    '/*',
    ' * js/data/' + file + '  --  GENERATED by tools/vectors/import-vectors.mjs, do not edit.',
    ...header.map((l) => ' * ' + l),
    ' */',
    "(function (WG) {",
    "  'use strict';",
    '  WG.define(' + JSON.stringify(moduleName) + ', Object.freeze(' + JSON.stringify(data) + '));',
    '})(window.WG);',
    '',
  ].join('\n');
  writeFileSync(join(dataDir, file), body);
  console.log('wrote js/data/' + file);
}

/** Parse "key = value" lines inside the first <pre> block of a BIP mediawiki file. */
function preKeyValues(text) {
  const pre = text.slice(text.indexOf('==Test vectors=='));
  const out = [];
  for (const line of pre.split(/\r?\n/)) {
    const m = line.match(/^\s*([a-zA-Z_]+)\s*=\s*(\S.*?)\s*$/);
    if (m) out.push([m[1], m[2]]);
    if (/^<\/pre>/.test(line.trim())) break;
  }
  return out;
}

const github = (repoName, commit, path) => 'https://github.com/' + repoName + '/blob/' + commit + '/' + path;

// ---- BIP39 (Trezor reference vectors, English, passphrase "TREZOR") -------
{
  const c = sha('trezor.sha');
  const raw = JSON.parse(read('bip39-vectors.json'));
  const cases = raw.english.map(([entropy, mnemonic, seed, xprv]) => ({ entropy, mnemonic, seed, xprv }));
  check(cases.length === 24, 'bip39 case count');
  emitVector('bip39-trezor.js', 'bip39Trezor', [
    'Source: ' + github('trezor/python-mnemonic', c, 'vectors.json'),
    'Each case: entropy -> mnemonic (English) -> seed with passphrase "TREZOR" -> BIP32 root xprv.',
  ], { source: 'trezor/python-mnemonic@' + c, passphrase: 'TREZOR', cases });
}

// ---- BIP32 (test vectors 1-4 from the BIP text) -----------------------------
{
  const c = sha('bips.sha');
  const vectors = [];
  let cur = null, chain = null;
  for (const line of read('bip-0032.mediawiki').split(/\r?\n/)) {
    let m;
    if ((m = line.match(/^===Test vector (\d+)===/))) { cur = { name: 'Test vector ' + m[1], seed: null, chains: [] }; vectors.push(cur); chain = null; }
    else if (cur && (m = line.match(/^Seed \(hex\): ([0-9a-f]+)/))) cur.seed = m[1];
    else if (cur && (m = line.match(/^\* Chain (\S+)/))) { chain = { path: m[1].replace(/<sub>H<\/sub>/g, "'"), xpub: null, xprv: null }; cur.chains.push(chain); }
    else if (chain && (m = line.match(/^\*\* ext pub: (\S+)/))) chain.xpub = m[1];
    else if (chain && (m = line.match(/^\*\* ext prv: (\S+)/))) chain.xprv = m[1];
  }
  const valid = vectors.filter((v) => v.seed && v.chains.length && v.chains.every((ch) => ch.xpub && ch.xprv));
  check(valid.length >= 4, 'bip32 vector count');
  emitVector('bip32.js', 'bip32', [
    'Source: ' + github('bitcoin/bips', c, 'bip-0032.mediawiki'),
    'Each vector: master seed -> list of derivation paths with expected xpub/xprv.',
  ], { source: 'bitcoin/bips@' + c, vectors: valid });
}

// ---- BIP84 / BIP86 (abandon x11 about) -----------------------------------------
{
  const c = sha('bips.sha');
  /** Group key/values into {path, ...} entries using the "// ... = m/..." comments. */
  function bipAccounts(file) {
    const text = read(file);
    const mnemonic = (text.match(/mnemonic\s*=\s*(.+)/) || [])[1].trim();
    const entries = [];
    let cur = null;
    for (const line of text.slice(text.indexOf('==Test vectors==')).split(/\r?\n/)) {
      const p = line.match(/\/\/.*=\s*(m\/[0-9'\/]+)/);
      if (p) { cur = { path: p[1] }; entries.push(cur); continue; }
      const kv = line.match(/^\s*([a-zA-Z_]+)\s*=\s*(\S+)\s*$/);
      if (kv && cur) cur[kv[1]] = kv[2];
      if (line.trim() === '</pre>') break;
    }
    return { mnemonic, entries: entries.filter((e) => e.address) };
  }
  const b84 = bipAccounts('bip-0084.mediawiki');
  check(b84.entries.length === 3 && b84.entries[0].address === 'bc1qcr8te4kr609gcawutmrza0j4xv80jy8z306fyu', 'bip84 parse');
  const b86 = bipAccounts('bip-0086.mediawiki');
  check(b86.entries.length === 3 && b86.entries[0].address.startsWith('bc1p'), 'bip86 parse');
  emitVector('bip84-bip86.js', 'bip84bip86', [
    'Source: ' + github('bitcoin/bips', c, 'bip-0084.mediawiki') + ' and bip-0086.mediawiki',
    'Mnemonic "abandon x11 about", no passphrase. BIP84 gives WIF privkey/pubkey/address, BIP86 gives internal/output key/address.',
  ], { source: 'bitcoin/bips@' + c, bip84: b84, bip86: b86 });
}

// ---- BIP38 (non-EC-multiply only) -------------------------------------------
{
  const c = sha('bips.sha');
  const text = read('bip-0038.mediawiki');
  const cases = [];
  for (const [title, compressed] of [['===No compression, no EC multiply===', false], ['===Compression, no EC multiply===', true]]) {
    const section = text.slice(text.indexOf(title), text.indexOf('===', text.indexOf(title) + title.length));
    const re = /\*Passphrase: (.+)\n\*Encrypted: (\S+)\n\*Unencrypted \(WIF\): (\S+)\n\*Unencrypted \(hex\): ([0-9A-F]+)/g;
    let m;
    while ((m = re.exec(section.replace(/\r/g, '')))) cases.push({ compressed, passphrase: m[1], encrypted: m[2], wif: m[3], privkey: m[4].toLowerCase() });
  }
  check(cases.length === 4, 'bip38 case count ' + cases.length);
  emitVector('bip38.js', 'bip38', [
    'Source: ' + github('bitcoin/bips', c, 'bip-0038.mediawiki') + ' (sections "no EC multiply")',
  ], { source: 'bitcoin/bips@' + c, cases });
}

// ---- SLIP-0010 ed25519 ------------------------------------------------------
{
  const c = sha('slips.sha');
  const text = read('slip-0010.md');
  const vectors = [];
  for (const n of [1, 2]) {
    const start = text.indexOf('### Test vector ' + n + ' for ed25519');
    check(start !== -1, 'slip10 vector ' + n);
    const section = text.slice(start, text.indexOf('###', start + 10));
    const seed = section.match(/Seed \(hex\): ([0-9a-f]+)/)[1];
    const chains = [];
    const re = /\* Chain (\S+)\s*\n\s*\* fingerprint: [0-9a-f]+\s*\n\s*\* chain code: ([0-9a-f]+)\s*\n\s*\* private: ([0-9a-f]+)\s*\n\s*\* public: ([0-9a-f]+)/g;
    let m;
    while ((m = re.exec(section.replace(/\r/g, '')))) chains.push({ path: m[1].replace(/<sub>H<\/sub>/g, "'"), chainCode: m[2], privateKey: m[3], publicKey: m[4] });
    check(chains.length >= 5, 'slip10 chains in vector ' + n);
    vectors.push({ name: 'SLIP-0010 ed25519 vector ' + n, seed, chains });
  }
  emitVector('slip10-ed25519.js', 'slip10', [
    'Source: ' + github('satoshilabs/slips', c, 'slip-0010.md') + ' (ed25519 sections)',
    'public keys are 33 bytes: 0x00 || ed25519 public key.',
  ], { source: 'satoshilabs/slips@' + c, vectors });
}

// ---- SEP-0005 Stellar -------------------------------------------------------
{
  const c = sha('stellar.sha');
  const text = read('sep-0005.md').replace(/\r/g, '');
  const tests = [];
  const parts = text.split(/\n### Test \d+\n/).slice(1);
  for (const part of parts) {
    const blocks = [...part.matchAll(/```\n([\s\S]*?)\n```/g)].map((m) => m[1].trim());
    // "Mnemonic (24 words + BIP 39 passphrase)": the passphrase follows the
    // mnemonic inside the same code block, separated by a blank line.
    const [mnemonic, passphrase = ''] = blocks[0].split(/\n\s*\n/).map((s) => s.trim());
    const keysBlock = blocks[blocks.length - 1];
    const keys = keysBlock.split('\n').map((l) => l.trim().split(/\s+/)).filter((x) => x[0].startsWith("m/")).map(([path, address, secret]) => ({ path, address, secret }));
    if (keys.length) tests.push({ mnemonic, passphrase, keys });
  }
  check(tests.length >= 5 && tests[0].keys[0].address === 'GDRXE2BQUC3AZNPVFSCEZ76NJ3WWL25FYFK6RGZGIEKWE4SOOHSUJUJ6', 'sep5 parse');
  emitVector('sep5.js', 'sep5', [
    'Source: ' + github('stellar/stellar-protocol', c, 'ecosystem/sep-0005.md'),
    'Mnemonic (+ optional passphrase) -> m/44\'/148\'/n\' -> G... address and S... secret.',
  ], { source: 'stellar/stellar-protocol@' + c, tests });
}

