/*
 * tools/release/single-file.mjs
 *
 * PURPOSE
 *   Builds the one-file edition OfflineKey-Vault-<version>.html for phones.
 *   On Android, a file manager opens an HTML file through a content:// URL,
 *   where the browser cannot load the separate js/ and css/ files next to it.
 *   This edition inlines everything into a single page:
 *     - css/app.css                     -> one <style> element
 *     - every <script src> of index.html -> inline <script> (same order)
 *     - guide/tr.html, guide/en.html    -> <template id="guide-tr|en"> shown
 *                                          in-page by js/ui/app.js
 *
 * SECURITY
 *   The Content-Security-Policy keeps the network kill-switch and allows ONLY
 *   these exact inline scripts/styles, by their SHA-256 hashes (no
 *   'unsafe-inline'), so injected markup still cannot run code.
 *
 * USAGE
 *   import { buildSingleFile } from './single-file.mjs'   (used by make-zip.mjs
 *   and tools/browser-test/run.mjs); or `node tools/release/single-file.mjs <out.html>`.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

/** Base64 SHA-256 of a string, as used in CSP hash sources. */
const cspHash = (text) => "'sha256-" + createHash('sha256').update(text, 'utf8').digest('base64') + "'";

/** Text inside <div id="app" class="guide"> … </div> of a guide page. */
function guideBody(html) {
  const start = html.indexOf('<div id="app" class="guide">');
  const end = html.lastIndexOf('</div>');
  if (start < 0 || end < start) throw new Error('unexpected guide page layout');
  return html.slice(start + '<div id="app" class="guide">'.length, end);
}

/**
 * Build the single-file page.
 * @param {string} repo  repository root
 * @returns {string} complete HTML document
 */
export function buildSingleFile(repo) {
  // Line endings are normalised to LF: the HTML parser turns CRLF inside
  // <script>/<style> into LF before the browser hashes it for the CSP, so the
  // hashes below must be computed over LF text (jsPDF ships mixed endings).
  const read = (p) => readFileSync(join(repo, p), 'utf8').replace(/\r\n?/g, '\n');
  let html = read('index.html');
  const hashes = { script: [], style: [] };

  // Stylesheet -> <style>.
  const css = read('css/app.css');
  hashes.style.push(cspHash(css));
  html = html.replace('<link rel="stylesheet" href="css/app.css">', () => '<style>' + css + '</style>');

  // Every external script -> inline script (a literal "</script" would end the element early).
  html = html.replace(/<script src="([^"]+)"><\/script>/g, (m, src) => {
    const code = read(src).replace(/<\/script/gi, '<\\/script');
    hashes.script.push(cspHash(code));
    return '<script>' + code + '</script>';
  });

  // Guide pages as inert templates, inserted before the first script.
  const templates = ['tr', 'en'].map((l) => '<template id="guide-' + l + '">' + guideBody(read('guide/' + l + '.html')) + '</template>').join('\n');
  html = html.replace('<script>', () => templates + '\n<script>');

  // CSP: same policy, with the exact inline code allowed by hash.
  html = html.replace(/(<meta http-equiv="Content-Security-Policy" content=")([^"]+)(")/, (m, a, policy, z) => {
    const updated = policy
      .replace("script-src 'self'", 'script-src ' + hashes.script.join(' '))
      .replace("style-src 'self'", 'style-src ' + hashes.style.join(' '));
    if (updated === policy) throw new Error('CSP not updated');
    return a + updated + z;
  });
  // The note goes after the doctype (anything before it would switch browsers to quirks mode).
  if (!/^<!doctype html>/i.test(html)) throw new Error('index.html must start with <!doctype html>');
  return html.replace(/^<!doctype html>/i, '<!doctype html>\n<!-- OfflineKey Vault, single-file edition (generated by tools/release/single-file.mjs). -->');
}

// CLI: node tools/release/single-file.mjs <out.html>
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
  const out = process.argv[2] || join(repo, 'dist', 'OfflineKey-Vault.html');
  writeFileSync(out, buildSingleFile(repo));
  console.log('wrote ' + out);
}
